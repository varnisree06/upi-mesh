package com.demo.upi_offline_mesh.service;

import com.demo.upi_offline_mesh.model.Account;
import com.demo.upi_offline_mesh.model.PaymentInstruction;
import com.demo.upi_offline_mesh.model.TransactionStatus;
import com.demo.upi_offline_mesh.repository.AccountRepository;
import org.junit.jupiter.api.Test;

import java.time.Instant;
import java.util.Optional;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

class SettlementServiceTest {

    @Test
    void shouldTransferMoneyWhenPaymentIsDelivered() {

        AccountRepository repository =
                mock(AccountRepository.class);

        Account sender =
                new Account(
                        "Alice",
                        1000
                );

        Account receiver =
                new Account(
                        "Bob",
                        200
                );

        // Because Account IDs are generated by the database,
        // we need to mock the repository lookup.

        when(repository.findById(1L))
                .thenReturn(Optional.of(sender));

        when(repository.findById(2L))
                .thenReturn(Optional.of(receiver));

        SettlementService service =
                new SettlementService(repository);

        PaymentInstruction payment =
                createPayment();

        payment.setStatus(
                TransactionStatus.DELIVERED
        );

        service.settle(payment);

        assertEquals(
                500,
                sender.getBalance()
        );

        assertEquals(
                700,
                receiver.getBalance()
        );

        assertEquals(
                TransactionStatus.SETTLED,
                payment.getStatus()
        );

        verify(repository)
                .save(sender);

        verify(repository)
                .save(receiver);
    }


    @Test
    void shouldRejectSettlementWhenPaymentIsNotDelivered() {

        AccountRepository repository =
                mock(AccountRepository.class);

        SettlementService service =
                new SettlementService(repository);

        PaymentInstruction payment =
                createPayment();

        assertEquals(
                TransactionStatus.CREATED,
                payment.getStatus()
        );

        assertThrows(
                IllegalStateException.class,
                () -> service.settle(payment)
        );

        verifyNoInteractions(repository);
    }


    @Test
    void shouldRejectInsufficientBalance() {

        AccountRepository repository =
                mock(AccountRepository.class);

        Account sender =
                new Account(
                        "Alice",
                        300
                );

        Account receiver =
                new Account(
                        "Bob",
                        200
                );

        when(repository.findById(1L))
                .thenReturn(Optional.of(sender));

        when(repository.findById(2L))
                .thenReturn(Optional.of(receiver));

        SettlementService service =
                new SettlementService(repository);

        PaymentInstruction payment =
                createPayment();

        payment.setStatus(
                TransactionStatus.DELIVERED
        );

        assertThrows(
                IllegalStateException.class,
                () -> service.settle(payment)
        );

        // Balances must remain unchanged

        assertEquals(
                300,
                sender.getBalance()
        );

        assertEquals(
                200,
                receiver.getBalance()
        );

        verify(repository, never())
                .save(any(Account.class));
    }


    @Test
    void shouldRejectWhenSenderDoesNotExist() {

        AccountRepository repository =
                mock(AccountRepository.class);

        when(repository.findById(1L))
                .thenReturn(Optional.empty());

        SettlementService service =
                new SettlementService(repository);

        PaymentInstruction payment =
                createPayment();

        payment.setStatus(
                TransactionStatus.DELIVERED
        );

        assertThrows(
                IllegalStateException.class,
                () -> service.settle(payment)
        );
    }


    @Test
    void shouldRejectWhenReceiverDoesNotExist() {

        AccountRepository repository =
                mock(AccountRepository.class);

        Account sender =
                new Account(
                        "Alice",
                        1000
                );

        when(repository.findById(1L))
                .thenReturn(Optional.of(sender));

        when(repository.findById(2L))
                .thenReturn(Optional.empty());

        SettlementService service =
                new SettlementService(repository);

        PaymentInstruction payment =
                createPayment();

        payment.setStatus(
                TransactionStatus.DELIVERED
        );

        assertThrows(
                IllegalStateException.class,
                () -> service.settle(payment)
        );
    }


    private PaymentInstruction createPayment() {

        return new PaymentInstruction(
                UUID.randomUUID(),
                1L,
                2L,
                500,
                "INR",
                Instant.now(),
                UUID.randomUUID().toString()
        );
    }
}